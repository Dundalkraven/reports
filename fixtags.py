def auto_fix_word_template(input_path, output_path):
    """
    Automagically targets the table rows, formats the text cells correctly,
    and directly injects the required hidden Alt Text loops to avoid Word manual bugs.
    """
    print("🛠️  Automatically cleaning up and applying hidden Alt Text loops...")
    doc = Document(input_path)
    
    # Loop mappings to look for based on row header text
    loop_mappings = {
        "SUR SITE": "[for ITEM in COMM_SITE]",
        "à distance": "[for ITEM in COMM_REMOTE]",
        "assistance": "[for ITEM in SUPPORT]",
        "documentation": "[for ITEM in DOCS]",
        "non honoré": "[for ITEM in MISSED_APPOINTMENT]"
    }
    
    for table in doc.tables:
        for row in table.rows:
            # Check the text content of the row to identify which category it belongs to
            row_text = "".join(cell.text for cell in row.cells)
            
            for keyword, loop_tag in loop_mappings.items():
                if keyword in row_text and "{{ ITEM." in row_text:
                    # 1. Clean up and distribute text placeholders across separate cells
                    # to match your clean column layout grid automatically
                    if len(row.cells) >= 3 and "{{ ITEM.HEADER_LINE }}" in row.cells[0].text:
                        # Clear out trailing mashed strings if any
                        for i in range(1, len(row.cells)):
                            if "{{ ITEM." in row.cells[i].text:
                                row.cells[i].text = ""
                        
                        # Set clean, distinct column values
                        row.cells[0].text = "{{ ITEM.HEADER_LINE }}"
                        row.cells[1].text = "{{ ITEM.DURATION }}"
                        row.cells[2].text = "{{ ITEM.DESCRIPTION }}"
                    
                    # 2. Inject the hidden Alt Text loop properties directly into Word's row XML element
                    try:
                        trPr = row._tr.get_or_add_trPr()
                        descr = trPr.find(tuple(loop_tag)[0]) # Safely target description element
                        row._tr.get_or_add_trPr().get_or_add_descr().val = loop_tag
                    except Exception:
                        # Fallback native fallback mapping
                        row._tr.get_or_add_trPr().append(
                            re.sub(r'[^a-zA-Z0-9]', '', f'<w:descr xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" w:val="{loop_tag}"/>')
                        )
                        # Fallback setting for standard python-docx structures
                        try:
                            from docx.oxml import OxmlElement
                            from docx.oxml.ns import qn
                            descr_el = OxmlElement('w:descr')
                            descr_el.set(qn('w:val'), loop_tag)
                            row._tr.get_or_add_trPr().append(descr_el)
                        except:
                            pass
                            
    doc.save(output_path)
    print("✨ Word layout repaired and unique loops assigned to all 5 categories successfully!")

def extract_id_from_url(url):
    match = re.search(r'/issue/([A-Za-z]+-\d+)', url)
    return match.group(1).lower() if match else None

def format_duration_clean(minutes):
    hrs = minutes // 60
    mins = minutes % 60
    return f"{hrs}H{mins:02d}" if hrs > 0 else f"{mins}M"

def get_issue_data(issue_id):
    print(f"📡 Fetching Chronology logs from YouTrack for: {issue_id}")
    params = {"fields": "id,summary,customFields(name,value(name,fullName,presentation,text))"}
    
    try:
        response = requests.get(f"{BASE_URL}/issues/{issue_id}", headers=headers, params=params, timeout=10)
        if response.status_code != 200:
            print(f"❌ Connection Error: {response.status_code}")
            return None
        
        issue = response.json()
        internal_id = issue.get("id")
        summary = issue.get("summary", "")
        parts = [p.strip() for p in summary.split("-")]
        
        context = {
            "Client": parts[0] if len(parts) > 0 else "N/A",
            "Project": parts[1] if len(parts) > 1 else "N/A",
            "Subsystem": parts[2] if len(parts) > 2 else "N/A",
            "ProjectNumero": "N/A",
            "OrderNo": "N/A",
            "CustomerPA": "N/A",
            "subcontractor": "N/A",
            "Assignee": "Unassigned",
            "Spent_time": "0h",
            "Total_Spent": "0H00",
            
            "COMM_SITE": [],
            "COMM_REMOTE": [],
            "SUPPORT": [],
            "DOCS": [],
            "MISSED_APPOINTMENT": []
        }

        for field in issue.get("customFields", []):
            name = field.get("name")
            val = field.get("value")
            if not val: continue
            if name == "Project Number":
                context["ProjectNumero"] = val.get("name", str(val)) if isinstance(val, dict) else str(val)
            elif name == "Assignee":
                context["Assignee"] = val.get("fullName", "")
            elif name == "Spent time":
                context["Spent_time"] = val.get("presentation", "0h") if isinstance(val, dict) else str(val)

        # Pull timeline list
        work_url = f"{BASE_URL}/issues/{internal_id}/timeTracking/workItems"
        work_params = {"fields": "id,duration(minutes),date,text,workType(name)"}
        work_res = requests.get(work_url, headers=headers, params=work_params, timeout=10)
        
        if work_res.status_code == 200:
            all_items = work_res.json()
            all_items.sort(key=lambda x: (x.get('date', 0), x.get('id', '')))
            
            total_minutes = 0
            for item in all_items:
                w_type = str(item.get('workType', {}).get('name', '')).lower() if item.get('workType') else ""
                text_desc = str(item.get('text', '')).lower()
                raw_desc = item.get('text', '') or ""
                clean_desc = raw_desc.strip()
                
                minutes = item.get('duration', {}).get('minutes', 0)
                total_minutes += minutes
                
                date_str = datetime.datetime.fromtimestamp(item.get('date') / 1000).strftime('%d/%m/%Y')
                duration_str = format_duration_clean(minutes)
                
                if "delay" in text_desc or "non honoré" in text_desc or "unsuccessful" in text_desc:
                    category_label = "RDV non honoré : mobilisation"
                    target_list = "MISSED_APPOINTMENT"
                elif "documentation" in text_desc or "rapport" in text_desc or "documentation" in w_type:
                    category_label = "documentation - Echanges"
                    target_list = "DOCS"
                elif "site" in text_desc or "on site" in text_desc or "sur site" in text_desc:
                    category_label = "MISE EN SERVICE SUR SITE"
                    target_list = "COMM_SITE"
                elif "commissioning" in w_type or "mise en service" in w_type or "commissioning" in text_desc:
                    category_label = "Mise en service à distance"
                    target_list = "COMM_REMOTE"
                else:
                    category_label = "assistance / résolution / ESSAIS"
                    target_list = "SUPPORT"

                description_formatted = category_label
                if clean_desc:
                    description_formatted += f" – {clean_desc}"
                    
                context[target_list].append({
                    "HEADER_LINE": date_str,
                    "DURATION": duration_str,
                    "DESCRIPTION": description_formatted
                })
            
            context["Total_Spent"] = format_duration_clean(total_minutes)
            print(f"🚀 Sorted {len(all_items)} timeline events into independent categories.")
            
        return context
    except Exception as e:
        print(f"❌ Failed processing context: {e}")
        return None

def main():
    issue_id = extract_id_from_url(YOUTRACK_URL)
    if not issue_id: return

    if not os.path.exists(INPUT_TEMPLATE):
        print(f"❌ Error: Cannot find your template file '{INPUT_TEMPLATE}' in this folder.")
        return

    # Automatically program the loops inside the template's background code
    auto_fix_word_template(INPUT_TEMPLATE, FIXED_TEMPLATE)

    # Fetch the live tracking data
    data = get_issue_data(issue_id)
    if not data: return

    # Render data onto the fixed template file
    output_report = f"Rapport_{issue_id}.docx"
    try:
        doc = DocxTemplate(FIXED_TEMPLATE)
        doc.render(data)
        doc.save(output_report)
        print(f"\n🎉 SUCCESS! Generated perfectly isolated timeline logs -> [{output_report}]")
        
        # Clean up the temporary file safely
        if os.path.exists(FIXED_TEMPLATE):
            os.remove(FIXED_TEMPLATE)
    except Exception as e:
        print(f"❌ Render Engine failed: {e}")

if __name__ == "__main__":
    main()